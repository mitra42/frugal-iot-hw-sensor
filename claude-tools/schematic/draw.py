"""Readable schematic for Frugal-IoT V0.2, drawn with schlib
(Diode663/kicad-claude-skills, MIT). circuit.py is the source of truth for
parts and nets; this file and dblk.py only decide where things are drawn.

    <KiCad python> draw.py [--lint-only]
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from schlib import Design
import dbase, dblk

PROJ = os.path.normpath(os.path.join(HERE, '..', '..', 'frugal_iot_v02'))

def main():
    d = Design(PROJ, 'frugal_iot_v02', title='Frugal-IoT V0.2', rev='0.2',
               company='Natural Innovation')
    parts = {r: (p['lib'], p['value'], p['props']['Footprint'], p['props']) for r, p in dbase.PARTS.items()}
    d.lint(parts, dbase.NETS, dbase.NO_CONNECT)
    if '--lint-only' in sys.argv:
        return
    s = d.sheet('frugal_iot_v02.kicad_sch', 'Frugal-IoT V0.2', paper='auto',
                comment='Generated by claude-tools/schematic/draw.py from circuit.py -- edit those, not this file')
    dbase.S = s
    dblk.usb(101.6, 101.6)
    dblk.charger(406.4, 121.92)
    dblk.syspwr(812.8, 101.6)
    dblk.module(203.2, 508.0)
    dblk.conn(609.6, 508.0)
    dblk.rs485(1016.0, 508.0)
    s.arrange()
    d.write(force=True, strict=('--strict' in sys.argv))
    ok = d.verify(dbase.NETS, dbase.NO_CONNECT)
    d.erc()
    d.check_text()
    print('VERIFY', 'OK' if ok else 'FAIL')

if __name__ == '__main__':
    main()
